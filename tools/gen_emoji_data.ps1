# Generates font\emoji_data.odin (the Emoji and Emoji_Presentation properties as sorted ranges) from Unicode's emoji-data.txt.
#   tools\fetch_emoji.ps1 -Unicode ; tools\gen_emoji_data.ps1 [-Data build\emoji\emoji-data.txt]
param([string]$Data = '')
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
if (-not $Data) { $Data = Join-Path $root 'build\emoji\emoji-data.txt' }
$version = ((Get-Content $Data -Encoding UTF8 | Where-Object { $_ -match '^# Version' } | Select-Object -First 1) -replace '[^0-9.]', '')
$ranges = @{ Emoji = @(); Emoji_Presentation = @() }
foreach ($l in Get-Content $Data -Encoding UTF8) {
	if ($l -notmatch '^([0-9A-F]+)(\.\.([0-9A-F]+))?\s*;\s*(\w+)\s*#') { continue }
	$prop = $Matches[4]
	if (-not $ranges.ContainsKey($prop)) { continue }
	$a = [Convert]::ToInt32($Matches[1], 16)
	$b = if ($Matches[3]) { [Convert]::ToInt32($Matches[3], 16) } else { $a }
	$ranges[$prop] += , @($a, $b)
}
function Emit($name, $list) {
	$list = $list | Sort-Object { $_[0] }
	# merge neighbours
	$m = @()
	foreach ($r in $list) {
		if ($m.Count -gt 0 -and $m[-1][1] + 1 -ge $r[0]) { if ($r[1] -gt $m[-1][1]) { $m[-1][1] = $r[1] } } else { $m += , @($r[0], $r[1]) }
	}
	$sb = New-Object Text.StringBuilder
	[void]$sb.AppendLine("@(rodata)`n$name := [?][2]rune{")
	$line = "`t"
	foreach ($r in $m) {
		$item = '{' + ('0x{0:X}, 0x{1:X}' -f $r[0], $r[1]) + '}, '
		if ($line.Length + $item.Length -gt 118) { [void]$sb.AppendLine($line.TrimEnd()); $line = "`t" }
		$line += $item
	}
	[void]$sb.AppendLine($line.TrimEnd())
	[void]$sb.AppendLine('}')
	$sb.ToString()
}
$out = "package font`n`n// Generated by tools\gen_emoji_data.ps1 from Unicode $version emoji-data.txt (the file tools\fetch_emoji.ps1 -Unicode pins). Do not edit.`n`n"
$out += "// Emoji=Yes: characters that have an emoji presentation (with U+FE0F, or by default).`n" + (Emit 'EMOJI_RANGES' $ranges['Emoji']) + "`n"
$out += "// Emoji_Presentation=Yes: characters drawn as emoji unless U+FE0E follows.`n" + (Emit 'EMOJI_PRESENTATION_RANGES' $ranges['Emoji_Presentation'])
[IO.File]::WriteAllText((Join-Path $root 'font\emoji_data.odin'), ($out -replace "`r`n", "`n"), [Text.UTF8Encoding]::new($false))
Write-Host "font\emoji_data.odin: Unicode $version, $($ranges['Emoji'].Count) + $($ranges['Emoji_Presentation'].Count) ranges (before merging)"
